def dash_json():
    return json.dumps(dashboard(), indent=2, ensure_ascii=False) + "\n"


def bound_properties(node=None):
    """Every SimCastPlugin.<name> the dashboard reads."""
    s = json.dumps(dashboard() if node is None else node)
    return set(re.findall(r"\[" + re.escape(P) + r"([A-Za-z0-9_.]+)\]", s))


# ----------------------------------------------------------------------------------------------- preview
def demo_values(laps=6, race_s=150.0):
    """The values the plugin would publish part-way through a demo race (stopped race_s into it)."""
    from simcast import app
    cast = app.headless_run(laps=laps, seed=7, log=lambda *a: None, max_t=race_s)
    st = cast._state()
    st["source"], st["on_air"], st["speaking"] = "Le Mans Ultimate", True, True
    cfg = dict(cast.config(), hotkey_skip="key:F9", hotkey_mute="key:F10", hotkey_me="joy:Fanatec Wheel#6")
    if st["lines"]:
        st["lines"][-1] = dict(st["lines"][-1], t=1000.0)
    d = simhub.snapshot(st, cfg, now=1002.0)
    d.update({"Connected": True, "Disconnected": False, "Port": simhub.PORT})
    return d


def _color(c):
    c = c.lstrip("#")
    if len(c) == 8:
        a, r, g, b = (int(c[i:i + 2], 16) for i in range(0, 8, 2))
        return (r, g, b, a)
    return tuple(int(c[i:i + 2], 16) for i in range(0, 6, 2)) + (255,)


def _eval(expr, vals):
    if expr == NOT_CONNECTED:
        return not vals.get("Connected")
    m = re.fullmatch(r"\[" + re.escape(P) + r"(.+)\]", expr)
    return vals.get(m.group(1)) if m else None


def preview(path, screen_ix=0, connected=True):
    from PIL import Image, ImageDraw, ImageFont
    vals = demo_values() if connected else {"Connected": False}
    fonts = {}

    def font(size, weight):
        bold = weight in ("Bold", "SemiBold")
        key = (int(size), bold)
        if key not in fonts:
            name = "DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"
            try:
                fonts[key] = ImageFont.truetype(name, int(size * 0.92))
            except OSError:
                fonts[key] = ImageFont.load_default()
        return fonts[key]

    d = dashboard()
    img = Image.new("RGBA", (W, H), _color(d["BackgroundColor"]))
    over = []

    def draw(items, ox=0.0, oy=0.0):
        for it in items:
            b = it.get("Bindings", {})
            if "Visible" in b and not _eval(b["Visible"]["Formula"]["Expression"], vals):
                continue
            g = lambda k, dflt: (_eval(b[k]["Formula"]["Expression"], vals) if k in b else None) or dflt  # noqa
            x, y, w, h = it["Left"] + ox, it["Top"] + oy, it["Width"], it["Height"]
            t = it["$type"]
            if t.endswith("Layer, SimHub.Plugins"):
                draw(it["Childrens"], ox, oy)
                continue
            layer_ = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            dr = ImageDraw.Draw(layer_)
            bg = _color(g("BackgroundColor", it.get("BackgroundColor", CLEAR)))
            if bg[3]:
                dr.rectangle([x, y, x + w - 1, y + h - 1], fill=bg)
            if "IsTextItem" in it:
                s = str(g("Text", it.get("Text", "")))
                if s:
                    f = font(it["FontSize"], it["FontWeight"])
                    tw = dr.textlength(s, font=f)
                    if tw > w:
                        over.append((it["Name"], s, int(tw), int(w)))
                    tx = x if it["HorizontalAlignment"] == LEFT else (x + (w - tw) / 2 if it["HorizontalAlignment"]
                                                                       == CENTER else x + w - tw)
                    asc, desc = f.getmetrics()
                    ty = y + (h - asc - desc) / 2
                    dr.text((tx, ty), s, font=f, fill=_color(g("TextColor", it["TextColor"])))
            img.alpha_composite(layer_)

    draw(d["Screens"][screen_ix]["Items"])
    img.convert("RGB").save(path)
    return over


# ----------------------------------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--preview")
    ap.add_argument("--screen", type=int, default=0)
    ap.add_argument("--disconnected", action="store_true")
    a = ap.parse_args()
    if a.preview:
        over = preview(a.preview, a.screen, not a.disconnected)
        for name, s, tw, w in over:
            print(f"too wide: {name}: {tw} > {w}: {s!r}")
        print(f"wrote {a.preview}")
        return 0
    want = {KEYS_CS: keys_cs(), DASH: dash_json(), CSPROJ: csproj()}
    if a.check:
        stale = [p for p, s in want.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != s]
        for p in stale:
            print(f"out of date: {os.path.relpath(p, REPO)} (run tools/simhub/build_simhub.py)")
        missing = bound_properties() - set(plugin_keys()) - {"Connected", "Disconnected", "Port"}
        for k in sorted(missing):
            print(f"the dashboard reads {P}{k}, which the plugin doesn't publish")
        return 1 if stale or missing else 0
    for p, s in want.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(s)
        print(f"wrote {os.path.relpath(p, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
