#!/usr/bin/env python3
"""Builds SimCast's SimHub files from simcast/simhub.py, so the plugin, the dashboard and SimCast always agree:

  simhub/plugin/SimCastPlugin/Keys.g.cs           every property the plugin publishes, with its value while
                                                   SimCast isn't running
  simhub/dashboard/SimCast Booth/SimCast Booth.djson   the SimCast Booth dashboard (SimHub Dash Studio)

  python3 tools/simhub/build_simhub.py             write them
  python3 tools/simhub/build_simhub.py --check     exit 1 if either is out of date (the tests run this)
  python3 tools/simhub/build_simhub.py --preview out.png [--screen N] [--disconnected]
                                                   draw a screen of the dashboard, with a demo race's values
"""
