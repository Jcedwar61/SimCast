# ----------------------------------------------------------------------------------------------- the plugin's keys
def plugin_keys():
    """Every value simhub.snapshot() gives, with what it reads while SimCast isn't running: an empty race."""
    return simhub.snapshot({}, {}, now=0.0)


def _cs_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v) + "d"
    s = str(v).replace("\\", "\\\\").replace('"', '\\"')
    s = "".join(c if ord(c) < 128 else "\\u%04x" % ord(c) for c in s)
    return f'"{s}"'


def keys_cs():
    rows = [f'            new KeyValuePair<string, object>("{k}", {_cs_value(v)}),' for k, v in plugin_keys().items()]
    return ("// Generated by tools/simhub/build_simhub.py from simcast/simhub.py: don't edit by hand.\n"
            "// Every property the plugin publishes (SimCastPlugin.<name>) and its value while SimCast isn't running.\n"
            "using System.Collections.Generic;\n\n"
            "namespace SimCastForSimHub\n{\n    static class Keys\n    {\n"
            "        public static readonly KeyValuePair<string, object>[] All =\n        {\n"
            + "\n".join(rows) + "\n        };\n    }\n}\n")


# ----------------------------------------------------------------------------------------------- dashboard items
def _ids(name):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "simcast-simhub/" + name))      # stable, so rebuilds don't churn


def bind(target, expr, fmt=None):
    b = {"Formula": {"Expression": expr}, "Mode": 2, "TargetPropertyName": target}
    if fmt is not None:
        b = {"FormatString": fmt, **b}
    return b


def prop(name):
    return f"[{P}{name}]"


NOT_CONNECTED = f"if(isnull({prop('Connected')}, false), false, true)"   # also true with no plugin at all


def rect(name, x, y, w, h, color=PANEL, color_prop=None, visible=None, border=None):
    it = {"$type": "SimHub.Plugins.OutputPlugins.GraphicalDash.Models.RectangleItem, SimHub.Plugins",
          "IsRectangleItem": True, "BackgroundColor": color}
    if border:
        it["BorderStyle"] = border
    it.update({"Height": float(h), "Left": float(x), "Top": float(y), "Visible": True, "Width": float(w),
               "Name": name})
    b = {}
    if color_prop:
        b["BackgroundColor"] = bind("BackgroundColor", prop(color_prop))
    if visible:
        b["Visible"] = bind("Visible", visible if visible.startswith(("if(", "[")) else prop(visible))
    if b:
        it["Bindings"] = b
    return it


def text(name, x, y, w, h, value="", size=16.0, color=FG, weight="Normal", align=LEFT, valign=1, text_prop=None,
         color_prop=None, bg=CLEAR, bg_prop=None, visible=None):
    it = {"$type": "SimHub.Plugins.OutputPlugins.GraphicalDash.Models.TextItem, SimHub.Plugins",
          "IsTextItem": True, "Font": FONT, "FontWeight": weight, "FontSize": float(size), "Text": value,
          "TextColor": color, "HorizontalAlignment": align, "VerticalAlignment": valign, "BackgroundColor": bg,
          "Height": float(h), "Left": float(x), "Top": float(y), "Visible": True, "Width": float(w), "Name": name}
    b = {}
    if text_prop:
        b["Text"] = bind("Text", prop(text_prop), fmt="")
    if color_prop:
        b["TextColor"] = bind("TextColor", prop(color_prop))
    if bg_prop:
        b["BackgroundColor"] = bind("BackgroundColor", prop(bg_prop))
    if visible:
        b["Visible"] = bind("Visible", visible if visible.startswith(("if(", "[")) else prop(visible))
    if b:
        it["Bindings"] = b
    return it


def layer(name, items, visible=None, x=0, y=0, w=W, h=H):
    it = {"$type": "SimHub.Plugins.OutputPlugins.GraphicalDash.Models.Layer, SimHub.Plugins",
          "Top": float(y), "Left": float(x), "Height": float(h), "Width": float(w), "BackgroundColor": CLEAR,
          "Childrens": items, "Group": False, "Visible": True, "Name": name}
    if visible:
        it["Bindings"] = {"Visible": bind("Visible", visible if visible.startswith(("if(", "[")) else prop(visible))}
    return it


